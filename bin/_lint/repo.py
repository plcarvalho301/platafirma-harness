"""repo — predicados de conformidade de repositorio a arq:0042.

Modulo unico da regua (card #3153): `lint repo`, o pre-commit e `conferir repo` chamam as
mesmas funcoes daqui. `achados_de_repo`, `cabecalhos_ausentes` e `topos_nao_declarados`
sao o predicado; `verificar_repo` so os traduz em Apontamento. Quem so imprime diferente
(conferir) chama os predicados, nunca reescreve a regra.

O que o instrumento NAO faz: nao olha historico. Conformacao e para frente (0042), entao o
alvo e `git ls-files`, nunca `rev-list --all`. Limite declarado: render gerado so se
detecta por marca no cabecalho do arquivo; ferramenta que nao assina o que gera passa.
"""
from __future__ import annotations

import os
import subprocess
from pathlib import Path
from typing import Iterable, Optional

from .resultado import Apontamento

EXT_ACERVO = {
    ".epub", ".pdf", ".docx", ".doc", ".pptx", ".ppt", ".xlsx", ".xls",
    ".mobi", ".azw3", ".djvu", ".mp3", ".mp4", ".zip", ".tar", ".gz", ".7z",
}
EXT_GRANEL = {".jsonl", ".tsv", ".csv", ".dump", ".parquet", ".sqlite", ".db"}
EXT_RENDER = {".svg", ".png"}
# Artefato regeneravel a partir do proprio fonte versionado: nunca e fonte, e nao tem
# piso de tamanho — 1 KB de bytecode versionado ja e a classe errada de arquivo.
EXT_GERADO = {".pyc", ".pyo", ".class", ".o", ".so", ".egg-info"}
DIR_GERADO = (
    "__pycache__/", "node_modules/", ".venv/", "dist/", "build/",
    ".pytest_cache/", ".mypy_cache/", ".ruff_cache/", ".tox/",
)
EXT_FONTE_RENDER = {".mmd", ".mermaid", ".d2", ".drawio", ".dot", ".puml", ".xml"}
PISO_ARQUIVO = 1024 * 1024  # acima disto nao e fonte editada a mao
PISO_GRANEL = 256 * 1024    # dump, manifesto e indice: estado extraivel, mora no banco
MARCA_GERADOR = (b"Generated by", b"generated by", b"Generator:", b"Do not edit")
# SVG com `mxfile` embutido e o formato editavel do drawio: e fonte, nao render.
MARCA_EDITAVEL = (b"mxfile", b"mxGraphModel")
FORA = {"archi_base", "i-have-adhd"}  # outro dono: dubious ownership

GENEROS = ("procedimento", "referencia", "referência", "explicacao", "explicação")
CAMPOS = ("**Gênero:**", "**Público:**", "**Derivada na wiki:**")

ROTULOS = ("GERADO", "ACERVO", "GRANEL", "GORDO", "RENDER")

_O_QUE_FERE = {
    "GERADO": lambda ext, rel, tam: f"artefato regeneravel rastreado ({ext or rel})",
    "ACERVO": lambda ext, rel, tam: f"materia de acervo rastreada ({tam / 1048576:.2f} MB)",
    "GRANEL": lambda ext, rel, tam: f"dado a granel volumoso ({tam / 1024:.0f} KB > 256 KB)",
    "GORDO": lambda ext, rel, tam: f"arquivo acima do piso de tamanho ({tam / 1048576:.2f} MB > 1 MB)",
    "RENDER": lambda ext, rel, tam: "render de diagrama sem fonte irma de mesmo nome-base",
}
_CURA = {
    "GERADO": "remover do git e declarar no .gitignore ou .conferir-repo",
    "ACERVO": "mover para endereco da obra fora do git conforme ont:0072",
    "GRANEL": "mover para banco ou declarar excecao em .conferir-repo",
    "GORDO": "mover para armazenamento externo ou declarar excecao em .conferir-repo",
    "RENDER": "manter a fonte no mesmo diretorio com o mesmo nome-base",
}


def _sh(args: list[str], cwd: Optional[str | Path] = None) -> tuple[int, str, str]:
    try:
        p = subprocess.run(args, cwd=str(cwd) if cwd else None, capture_output=True, text=True)
        return p.returncode, p.stdout.strip(), p.stderr.strip()
    except Exception as e:
        return 1, "", str(e)


def excecoes(raiz: Path | str) -> list[str]:
    """`.conferir-repo` na raiz, linha `permite: <prefixo>  # motivo`. A excecao vale por
    estar escrita no repo, nao por ser justa: fica no diff, e quem a escreveu responde."""
    regras = []
    try:
        with open(os.path.join(str(raiz), ".conferir-repo"), encoding="utf-8") as f:
            for linha in f:
                linha = linha.split("#", 1)[0].strip()
                if linha.startswith("permite:"):
                    regras.append(linha.split(":", 1)[1].strip())
    except OSError:
        pass
    return regras


def documentos_de_operacao(raiz: Path | str) -> list[str]:
    """Os que o repo DECLARA como documento de operacao, em `docs/.operacao`.

    Declarado, nunca inferido: repo sem o arquivo nao e medido.
    """
    try:
        with open(os.path.join(str(raiz), "docs", ".operacao"), encoding="utf-8") as f:
            linhas = [l.split("#", 1)[0].strip() for l in f]
    except OSError:
        return []
    return [l for l in linhas if l]


def cabecalho_de_operacao(caminho: Path | str) -> Optional[str]:
    """Motivo da reprova, ou None quando o cabecalho esta la e completo."""
    try:
        with open(caminho, encoding="utf-8", errors="replace") as f:
            cabeca = "".join(f.readline() for _ in range(12))
    except OSError:
        return "arquivo declarado em docs/.operacao e nao existe"
    faltam = [c for c in CAMPOS if c not in cabeca]
    if faltam:
        return "sem " + ", ".join(faltam)
    linha = next((l for l in cabeca.splitlines() if "**Gênero:**" in l), "")
    valor = linha.split("**Gênero:**", 1)[1].split("·")[0].strip().lower()
    if valor not in GENEROS:
        return f"genero {valor!r} fora de procedimento|referencia|explicacao"
    return None


def gerado_por_ferramenta(caminho: Path | str) -> bool:
    try:
        with open(caminho, "rb") as f:
            cabeca = f.read(8192)
    except OSError:
        return False
    if any(m in cabeca for m in MARCA_EDITAVEL):
        return False
    return any(m in cabeca for m in MARCA_GERADOR)


def achados_de_repo(
    raiz: Path | str, sob_juizo: Iterable[str], arquivos: Iterable[str]
) -> tuple[dict[str, list[tuple[str, int]]], int]:
    """O predicado por arquivo: ({rotulo: [(rel, tam)]}, peso somado de sob_juizo).

    `arquivos` e todo o rastreado (para achar a fonte irma de um render); `sob_juizo` e o
    que se julga (tudo, o staged, ou o alvo).
    """
    raiz = str(raiz)
    arquivos = list(arquivos)
    bases = {os.path.splitext(a)[0]: os.path.splitext(a)[1].lower() for a in arquivos}
    fontes = {b for b, e in bases.items() if e in EXT_FONTE_RENDER}
    regras = excecoes(raiz)
    achados: dict[str, list[tuple[str, int]]] = {r: [] for r in ROTULOS}
    peso = 0
    for rel in sob_juizo:
        caminho = os.path.join(raiz, rel)
        try:
            tam = os.path.getsize(caminho)
        except OSError:
            continue
        peso += tam
        if any(rel.startswith(r) for r in regras):
            continue
        ext = os.path.splitext(rel)[1].lower()
        if ext in EXT_GERADO or any(d in rel + "/" for d in DIR_GERADO):
            achados["GERADO"].append((rel, tam))
        elif ext in EXT_ACERVO:
            achados["ACERVO"].append((rel, tam))
        elif ext in EXT_GRANEL and tam > PISO_GRANEL:
            achados["GRANEL"].append((rel, tam))
        elif tam > PISO_ARQUIVO:
            achados["GORDO"].append((rel, tam))
        if ext in EXT_RENDER:
            base = os.path.splitext(rel)[0]
            if gerado_por_ferramenta(caminho) and base not in fontes:
                achados["RENDER"].append((rel, tam))
            elif rel.endswith(".drawio.svg"):
                pass  # fonte e render no mesmo arquivo: o drawio reabre o proprio SVG
            elif base not in fontes:
                # fonte no mesmo diretorio com nome-base que so difere de sufixo: a 0042
                # exige o mesmo nome-base para render e fonte
                irma = [f for f in fontes
                        if os.path.dirname(f) == os.path.dirname(base)
                        and base.startswith(f) and base != f]
                if irma:
                    achados["RENDER"].append((rel, tam))
    return achados, peso


def cabecalhos_ausentes(
    raiz: Path | str, sob_juizo: Optional[Iterable[str]] = None
) -> list[tuple[str, str]]:
    """[(rel, motivo)] dos documentos de operacao sem cabecalho completo (arq:0049).
    Com `sob_juizo`, so os que estao nele."""
    filtro = set(sob_juizo) if sob_juizo is not None else None
    saida = []
    for rel in documentos_de_operacao(raiz):
        if filtro is not None and rel not in filtro:
            continue
        motivo = cabecalho_de_operacao(os.path.join(str(raiz), rel))
        if motivo:
            saida.append((rel, motivo))
    return saida


def topos_nao_declarados(raiz: Path | str, arquivos: Iterable[str]) -> Optional[list[str]]:
    """Diretorios de topo que o README nao declara; None quando nao ha README."""
    try:
        with open(os.path.join(str(raiz), "README.md"), encoding="utf-8", errors="replace") as f:
            readme = f.read()
    except OSError:
        return None
    topos = {a.split("/", 1)[0] + "/" for a in arquivos if "/" in a}
    return sorted(t for t in topos if t not in readme)


def verificar_repo(
    raiz: Path | str,
    staged: bool = False,
    alvo: Optional[str] = None,
) -> list[Apontamento]:
    """Verifica um repositorio conforme arq:0042 e devolve lista de Apontamento."""
    raiz = Path(raiz)
    rc_ls, out, _ = _sh(["git", "ls-files", "-z"], cwd=raiz)
    if rc_ls != 0:
        return [
            Apontamento(
                str(raiz), 1,
                "git ls-files falhou ao listar arquivos rastreados",
                "verificar estado do git",
                severidade="bloqueante",
            )
        ]

    arquivos = [p for p in out.split("\0") if p]
    if staged:
        _, st, _ = _sh(["git", "diff", "--cached", "--name-only", "--diff-filter=ACMR", "-z"], cwd=raiz)
        sob_juizo = [p for p in st.split("\0") if p]
    elif alvo:
        alvo_rel = str(Path(alvo))
        sob_juizo = [p for p in arquivos if p == alvo_rel or p.startswith(alvo_rel.rstrip("/") + "/")]
    else:
        sob_juizo = arquivos

    apontamentos: list[Apontamento] = []
    for rel, motivo in cabecalhos_ausentes(raiz, sob_juizo if (staged or alvo) else None):
        apontamentos.append(Apontamento(
            rel, 1,
            f"cabecalho de operacao ausente/incompleto: {motivo}",
            "acrescentar cabecalho de operacao com genero e publico conforme arq:0049",
            severidade="bloqueante", id="CABECALHO",
        ))

    achados, _ = achados_de_repo(raiz, sob_juizo, arquivos)
    for rotulo in ROTULOS:
        for rel, tam in achados[rotulo]:
            ext = os.path.splitext(rel)[1].lower()
            apontamentos.append(Apontamento(
                rel, 1, _O_QUE_FERE[rotulo](ext, rel, tam), _CURA[rotulo],
                severidade="bloqueante", id=rotulo,
            ))

    # README so no repositorio inteiro: o commit e o alvo nao respondem pelo topo
    if not staged and not alvo:
        mudos = topos_nao_declarados(raiz, arquivos)
        if mudos is None:
            apontamentos.append(Apontamento(
                "README.md", 1,
                "README ausente: conjunto de diretorios de topo nao declarado",
                "criar README.md declarando os diretorios de topo",
                severidade="aviso", id="README",
            ))
        elif mudos:
            apontamentos.append(Apontamento(
                "README.md", 1,
                f"README desatualizado: nao declara diretorios de topo: {' '.join(mudos)}",
                f"acrescentar {' '.join(mudos)} no README.md",
                severidade="aviso", id="README",
            ))

    return apontamentos
